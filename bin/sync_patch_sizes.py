#!/usr/bin/env python3
"""Regenerate (or check) assets/recommended_patch_sizes.json from Mussel's source.

mussel-nf tiles every model at Mussel's recommended size (MODEL_PATCH_SIZES),
checks its MPP against MODEL_TARGET_MPP, and pairs slide encoders with their
patch encoders as SLIDE_ENCODER_COMPATIBILITY does. Nextflow needs these when the
workflow is built, so they're kept in this asset; this script makes it a
generated copy of mussel/models/model_factory.py at a pinned Mussel ref,
parsed without importing Mussel (no torch etc. needed).

  sync_patch_sizes.py --ref <commit|tag>           rewrite the asset from that ref
  sync_patch_sizes.py --check                      fail if the asset differs from its pinned ref
  sync_patch_sizes.py --source path/to/model_factory.py [--check]   use a local file
"""
from __future__ import annotations

import argparse
import ast
import json
import sys
import urllib.request
from pathlib import Path

ASSET = Path(__file__).resolve().parents[1] / "assets" / "recommended_patch_sizes.json"
RAW = "https://raw.githubusercontent.com/pathology-data-mining/Mussel/{ref}/mussel/models/model_factory.py"


def fetch(ref: str) -> str:
    with urllib.request.urlopen(RAW.format(ref=ref), timeout=60) as r:
        return r.read().decode()


def parse(source: str) -> dict:
    """{"sizes": {code: px}, "target_mpp": {code: mpp}} from model_factory.py source."""
    tree = ast.parse(source)
    codes: dict[str, str] = {}
    tables: dict[str, dict] = {}
    for node in tree.body:
        if isinstance(node, ast.ClassDef) and node.name == "ModelType":
            for stmt in node.body:
                # NAME = id, "code", "path"
                if (isinstance(stmt, ast.Assign) and isinstance(stmt.value, ast.Tuple)
                        and len(stmt.value.elts) >= 2 and isinstance(stmt.value.elts[1], ast.Constant)):
                    codes[stmt.targets[0].id] = stmt.value.elts[1].value
        elif isinstance(node, (ast.Assign, ast.AnnAssign)):
            target = node.targets[0] if isinstance(node, ast.Assign) else node.target
            if isinstance(target, ast.Name) and target.id in ("MODEL_PATCH_SIZES", "MODEL_TARGET_MPP",
                                                              "SLIDE_ENCODER_COMPATIBILITY") \
                    and isinstance(node.value, ast.Dict):
                table = {}
                for k, v in zip(node.value.keys, node.value.values):
                    if isinstance(k, ast.Attribute) and isinstance(v, ast.Constant):
                        table[k.attr] = v.value
                    elif isinstance(k, ast.Attribute) and isinstance(v, ast.Attribute):
                        table[k.attr] = ("ModelType", v.attr)  # a model, mapped to its code below
                tables[target.id] = table
    if "MODEL_PATCH_SIZES" not in tables or not codes:
        raise ValueError("MODEL_PATCH_SIZES / ModelType not found in model_factory.py")

    def by_code(table):
        values = [v[1] for v in table.values() if isinstance(v, tuple)]
        unknown = sorted((set(table) | set(values)) - set(codes))
        if unknown:
            raise ValueError(f"model names without a ModelType code: {unknown}")
        return {codes[name]: codes[value[1]] if isinstance(value, tuple) else value
                for name, value in sorted(table.items(), key=lambda kv: codes[kv[0]])}

    return {"sizes": by_code(tables["MODEL_PATCH_SIZES"]),
            "target_mpp": by_code(tables.get("MODEL_TARGET_MPP", {})),
            "slide_encoders": by_code(tables.get("SLIDE_ENCODER_COMPATIBILITY", {}))}


def render(tables: dict, ref: str) -> str:
    doc = {
        "_comment": "Generated by bin/sync_patch_sizes.py from Mussel's mussel/models/model_factory.py "
                    "(MODEL_PATCH_SIZES, MODEL_TARGET_MPP, SLIDE_ENCODER_COMPATIBILITY) at _mussel_ref. "
                    "Do not edit by hand.",
        "_mussel_ref": ref,
        "sizes": tables["sizes"],
        "target_mpp": tables["target_mpp"],
        "slide_encoders": tables["slide_encoders"],
    }
    return json.dumps(doc, indent=2) + "\n"


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--ref", help="Mussel commit or tag (default: the asset's _mussel_ref)")
    ap.add_argument("--source", type=Path, help="local model_factory.py instead of fetching --ref")
    ap.add_argument("--check", action="store_true", help="compare instead of writing")
    args = ap.parse_args(argv)
    current = json.loads(ASSET.read_text()) if ASSET.exists() else {}
    ref = args.ref or current.get("_mussel_ref")
    if not args.source and not ref:
        ap.error("--ref (or a _mussel_ref in the asset) is required")
    source = args.source.read_text() if args.source else fetch(ref)
    rendered = render(parse(source), ref or str(args.source))
    if args.check:
        if rendered != ASSET.read_text():
            print(f"{ASSET} is out of date with Mussel {ref}; run bin/sync_patch_sizes.py --ref {ref}",
                  file=sys.stderr)
            return 1
        print(f"{ASSET.name} matches Mussel {ref}")
        return 0
    ASSET.write_text(rendered)
    print(f"wrote {ASSET} from Mussel {ref}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
